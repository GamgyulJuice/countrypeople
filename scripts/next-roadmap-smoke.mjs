import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { completeOnboarding } from './onboarding-helper.mjs';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', d => d.accept());
try {
  await page.clock.setFixedTime(new Date('2026-10-03T03:00:00Z'));
  await page.goto('http://127.0.0.1:5173/');
  await completeOnboarding(page);
  await page.evaluate(() => {
    const key = 'countrypeople.demo.v1', data = JSON.parse(localStorage.getItem(key));
    data.tasks = [['A', '지역 탐색', '2026-10-01'], ['B', '교육 준비', '2026-10-15'], ['C', '이주 준비', '2026-11-01']].map(([id, title, due_date]) => ({ id, title, due_date, user_id: 'demo-user', completed: false, category: '생활', policy_id: null }));
    localStorage.setItem(key, JSON.stringify(data));
  });
  await page.reload();
  await page.getByRole('button', { name: '나의 로드맵', exact: true }).click();
  const row = title => page.locator('.task-row').filter({ hasText: title });
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-14');
  await expect(row('교육 준비')).toContainText('2026-10-15 ~ 2026-10-31');
  await page.getByRole('button', { name: '캘린더 보기', exact: true }).click();
  await page.getByRole('button', { name: /^2026-10-08,/ }).click();
  await expect(page.locator('.calendar-agenda')).toContainText('지역 탐색');
  await page.getByRole('checkbox', { name: '지역 탐색 완료', exact: true }).click();
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-14');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('countrypeople.demo.v1')).tasks.find(t => t.id === 'A').due_date)).toBe('2026-10-01');
  await page.getByRole('button', { name: '완료', exact: true }).click();
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-14');
  await page.getByRole('button', { name: '전체', exact: true }).click();
  await page.getByRole('button', { name: '목록 보기', exact: true }).click();
  await page.getByRole('button', { name: '교육 준비 삭제', exact: true }).click();
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-31');
  await page.getByRole('button', { name: '할 일 추가', exact: true }).click();
  await page.getByRole('textbox', { name: '할 일', exact: true }).fill('새로운 중간 단계');
  await page.getByLabel('시작일', { exact: true }).fill('2026-10-07');
  await expect(page.getByLabel('종료일', { exact: true })).toHaveValue('2026-10-31');
  await expect(page.getByLabel('종료일', { exact: true })).toHaveAttribute('readonly', '');
  await page.getByRole('button', { name: '할 일 저장', exact: true }).click();
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-06');
  await expect(row('새로운 중간 단계')).toContainText('2026-10-07 ~ 2026-10-31');
  await page.reload();
  await page.getByRole('button', { name: '나의 로드맵', exact: true }).click();
  await expect(row('지역 탐색')).toContainText('2026-10-01 ~ 2026-10-06');
  await page.getByRole('button', { name: '캘린더 보기', exact: true }).click();
  await page.getByRole('button', { name: /^2026-10-20,/ }).click();
  await expect(page.locator('.calendar-agenda')).toContainText('새로운 중간 단계');
  const artifacts = new URL('../artifacts/', import.meta.url);
  await mkdir(artifacts, { recursive: true });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: fileURLToPath(new URL('next-roadmap-desktop.png', artifacts)), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: fileURLToPath(new URL('next-roadmap-mobile.png', artifacts)), fullPage: true, animations: 'disabled' });
  expect(errors).toEqual([]);
  console.log('PASS: existing single-date tasks become successive periods immediately, complete/filter preserves boundaries, delete/insert recalculates, readonly derived end, reload and mobile.');
} finally { await browser.close(); }
